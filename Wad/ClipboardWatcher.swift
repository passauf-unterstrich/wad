// ClipboardWatcher.swift
// Bemerkt, wenn der Nutzer selbst Text kopiert, für den Zwischenablage-Verlauf (SPEC 1.6).
// Erkannt wird das am Änderungszähler der Zwischenablage, nie über die Tastatur (SPEC 2.1).
// macOS meldet Änderungen der Zwischenablage nicht, deshalb ist das eine der zwei bewussten
// Dauerabfragen in Wad: zweimal pro Sekunde eine einzige Zahl vergleichen.

import AppKit

final class ClipboardWatcher {
    static let interval: TimeInterval = 0.5

    /// Markierungen nach nspasteboard.org. So gekennzeichnete Inhalte kommen nie in den Verlauf:
    /// Passwörter aus Passwort-Managern, vorübergehende Inhalte wie Wads eigener Diktat-Text
    /// und automatisch erzeugte Inhalte.
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Meldet jeden neu kopierten Text.
    var onCopy: ((String) -> Void)?

    private let pasteboard: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?

    /// Was beim Start schon in der Zwischenablage liegt, zählt nicht als neu kopiert.
    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChange = pasteboard.changeCount
    }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: Self.interval, repeats: true) { [weak self] _ in
            self?.check()
        }
    }

    /// Übergeht den jetzigen Stand der Zwischenablage, etwa nachdem Wad sie kurz selbst benutzt hat.
    func skipCurrentChange() {
        lastChange = pasteboard.changeCount
    }

    /// Vergleicht den Änderungszähler und liest nur bei einer Änderung den Inhalt.
    func check() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard let types = pasteboard.types,
              Self.ignoredTypes.isDisjoint(with: types),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        onCopy?(text)
    }
}
